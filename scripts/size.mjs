#!/usr/bin/env node
// Reports dist/ size against the Playables budget (CLAUDE.md rule 2): the whole folder, and the
// "initial load" = everything Boot fetches before GameReady (index.html, bundle, Bridge runtime
// and config, atlas index, UI + first-theme atlases, first-theme backgrounds, audio index and one
// audio format). `--report <file>` also writes docs/size-report.md.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { join, relative } from 'node:path';

const DIST = new URL('../dist/', import.meta.url).pathname;
const TARGET = 8 * 1024 * 1024;
const HARD = 30 * 1024 * 1024;

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, out);
    else out.push({ path: relative(DIST, p), size: st.size });
  }
  return out;
}

const mb = (n) => (n / 1024 / 1024).toFixed(2) + ' MB';
const kb = (n) => Math.round(n / 1024) + ' KB';

/** Files fetched before GameReady, in load order (src/game/scenes/BootScene.ts). */
const FIRST_THEME = 'kitchen';
// Unlocks at level 4 (GDD v1.4), so Boot preloads it for a fresh player (lookahead 3 levels).
const SECOND_THEME = 'beach';
const INITIAL = [
  /^index\.html$/,
  /^assets\/index-[^/]+\.js$/,
  /^playgama-bridge\.js$/,
  /^playgama-bridge-config\.json$/,
  /^atlases\/index\.json$/,
  /^atlases\/ui\.(png|json)$/,
  new RegExp(`^atlases/${FIRST_THEME}\\.(png|json)$`),
  new RegExp(`^backgrounds/${FIRST_THEME}(_spot)?\\.png$`),
  new RegExp(`^atlases/${SECOND_THEME}\\.(png|json)$`),
  new RegExp(`^backgrounds/${SECOND_THEME}(_spot)?\\.png$`),
  /^audio\/index\.json$/,
];
const AUDIO_OGG = /^audio\/.+\.ogg$/;
const AUDIO_M4A = /^audio\/.+\.m4a$/;

let files;
try {
  files = walk(DIST);
} catch {
  console.error('dist/ not found. Run `npm run build` first.');
  process.exit(1);
}

// the test build (dist/test, published at /test/) is not part of the submission
const shipped = files.filter((f) => !f.path.startsWith('test/'));
const total = shipped.reduce((s, f) => s + f.size, 0);
shipped.sort((a, b) => b.size - a.size);

const initialBase = shipped.filter((f) => INITIAL.some((re) => re.test(f.path)));
const ogg = shipped.filter((f) => AUDIO_OGG.test(f.path));
const m4a = shipped.filter((f) => AUDIO_M4A.test(f.path));
const sum = (list) => list.reduce((s, f) => s + f.size, 0);
const initialOgg = sum(initialBase) + sum(ogg);
const initialM4a = sum(initialBase) + sum(m4a);

console.log(`dist/ total: ${mb(total)} in ${shipped.length} files (dist/test excluded)`);
console.log(
  `initial load (before GameReady): ${mb(initialOgg)} with OGG audio · ${mb(initialM4a)} with M4A (Safari)`,
);
console.log('largest files:');
for (const f of shipped.slice(0, 10)) console.log(`  ${mb(f.size).padStart(10)}  ${f.path}`);

const reportIdx = process.argv.indexOf('--report');
if (reportIdx !== -1) {
  const out = process.argv[reportIdx + 1];
  let commit = 'unknown';
  try {
    commit = execSync('git rev-parse --short HEAD', { encoding: 'utf8' }).trim();
  } catch {
    /* no git */
  }
  const date = new Date().toISOString().slice(0, 10);
  const row = (f) => `| ${f.path} | ${kb(f.size)} |`;
  const lines = [
    '# Size report',
    '',
    `Generated by \`npm run size -- --report docs/size-report.md\` on ${date} at commit ${commit}.`,
    'Budget (CLAUDE.md rule 2): initial load ≤ 8 MB target, ≤ 30 MB hard; no file > 30 MB; no',
    'build-time compression. The development build published at /test/ is excluded.',
    '',
    '## Totals',
    '',
    '| Measure | Size |',
    '| --- | --- |',
    `| dist/ shipped total | ${mb(total)} (${String(shipped.length)} files) |`,
    `| Initial load, OGG browsers (Chrome, Android, the YouTube app) | ${mb(initialOgg)} |`,
    `| Initial load, M4A browsers (Safari) | ${mb(initialM4a)} |`,
    `| Other themes, loaded from the bundle ahead of their first level | ${mb(total - initialOgg - sum(m4a))} |`,
    '',
    '## Initial load, file by file (load order of BootScene)',
    '',
    '| File | Size |',
    '| --- | --- |',
    ...initialBase.map(row),
    `| audio/*.ogg (${String(ogg.length)} files) | ${kb(sum(ogg))} |`,
    `| audio/*.m4a (${String(m4a.length)} files, Safari instead of OGG) | ${kb(sum(m4a))} |`,
    '',
    '## Largest shipped files',
    '',
    '| File | Size |',
    '| --- | --- |',
    ...shipped.slice(0, 10).map(row),
    '',
    `Verdict: ${initialM4a <= TARGET ? 'within the 8 MB target' : initialM4a <= HARD ? 'ABOVE the 8 MB target, under the 30 MB hard limit' : 'ABOVE THE 30 MB HARD LIMIT'}.`,
    '',
  ];
  writeFileSync(out, lines.join('\n'));
  console.log(`report written to ${out}`);
}

let failed = false;
for (const f of shipped) {
  if (f.size > HARD) {
    console.error(`FAIL: ${f.path} is ${mb(f.size)} (> 30 MB single-file limit)`);
    failed = true;
  }
}
if (initialM4a > HARD) {
  console.error(`FAIL: initial load ${mb(initialM4a)} exceeds the 30 MB hard limit`);
  failed = true;
} else if (initialM4a > TARGET) {
  console.warn(`WARN: initial load ${mb(initialM4a)} exceeds the 8 MB target`);
}
if (total > HARD) {
  console.error(`FAIL: total ${mb(total)} exceeds the 30 MB hard limit`);
  failed = true;
}
process.exit(failed ? 1 : 0);
